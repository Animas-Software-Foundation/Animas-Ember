#!/usr/bin/env python3
"""Generates docs/data.js, the data the website needs: map layouts, the anima roster,
the cast, and the font metrics. It reads the same files the Godot game uses, so the site
can't drift from the game. Run it after changing maps, animas, characters, or the font:

    python3 tools/build_site_data.py
"""
import json
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
rd = lambda p: open(os.path.join(ROOT, p)).read()

maps = {}
for name in ("town", "house", "route1"):
    block = re.search(r"rows = PackedStringArray\(\[(.*?)\]\)", rd(f"scenes/maps/{name}.gd"), re.S).group(1)
    maps[name] = re.findall(r'"([^"]+)"', block)
    assert len({len(r) for r in maps[name]}) == 1, f"{name}: rows differ in length"

def entries(path, key):
    return [json.loads(l.strip().rstrip(",")) for l in rd(path).splitlines() if l.strip().startswith('{"' + key + '"')]

animas = [{k: a[k] for k in ("id", "name", "types", "stage", "stages", "stats", "dex", "evolves_to", "evolve_level")} for a in entries("scripts/data/anima_roster.gd", "id")]
cast = entries("scripts/data/character_roster.gd", "id")
fnt = rd("assets/fonts/animas_pixel.fnt")
fm = {int(i): [int(x), int(y), int(w), int(a)] for i, x, y, w, a in re.findall(r"char id=(\d+) x=(\d+) y=(\d+) width=(\d+) height=\d+ .*?xadvance=(\d+)", fnt)}
dump = lambda o: json.dumps(o, separators=(",", ":"))
out = "// GENERATED by tools/build_site_data.py from the game's own files. Do not edit by hand.\n"
out += "const MAP_ROWS=%s;\nconst ANIMAS=%s;\nconst CAST=%s;\nconst FM=%s;\n" % (dump(maps), dump(animas), dump(cast), dump(fm))
open(os.path.join(ROOT, "docs/data.js"), "w").write(out)
print("docs/data.js:", len(out) // 1024, "KB |", {k: (len(v[0]), len(v)) for k, v in maps.items()}, "| animas", len(animas), "| cast", len(cast))
